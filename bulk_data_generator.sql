-- =====================================================================
-- BULK DATA GENERATOR
-- Run this AFTER ai_text_evaluation_schema.sql (schema + seed data)
-- This adds thousands of synthetic rows so the database is large
-- enough for realistic analysis using joins, aggregation,
-- window functions, and views.
--
-- NOTE: This version deliberately injects some messy data (duplicate
-- prompts, inconsistent casing, extra whitespace, missing values) so
-- there is real work to do in the Data Cleaning section of
-- analysis_queries.sql. In a real scraped/collected dataset this kind
-- of mess happens naturally; here it's added on purpose so the
-- cleaning step reflects the kind of issues that often appear in
-- real-world datasets.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. More evaluators (10 total, on top of the 2 from seed data)
-- ---------------------------------------------------------------------
INSERT INTO evaluators (evaluator_name, evaluator_type, expertise_area)
SELECT
    'Evaluator_' || i,
    (ARRAY['human', 'expert', 'llm_judge'])[floor(random() * 3 + 1)],
    (ARRAY['ESL teaching', 'linguistics', 'general', 'computational linguistics'])[floor(random() * 4 + 1)]
FROM generate_series(1, 10) AS s(i);


-- ---------------------------------------------------------------------
-- 2. 2,000 prompts, built from templates.
--    Categories are inserted with INCONSISTENT CASING/WHITESPACE on
--    purpose (e.g. 'Summarization', 'SUMMARIZATION ', ' coding') to
--    simulate messy data entry. This gets fixed in the cleaning step.
-- ---------------------------------------------------------------------
INSERT INTO prompts (prompt_text, category, difficulty_level)
SELECT
    (ARRAY[
        'Summarize the following passage about ',
        'Explain the concept of ',
        'Translate this sentence about ',
        'Write a short story involving ',
        'Correct the grammar in this sentence about ',
        'Give three tips for improving writing about '
    ])[floor(random() * 6 + 1)]
    || (ARRAY[
        'climate change', 'the French Revolution', 'machine learning',
        'a lonely astronaut', 'a business negotiation', 'space travel',
        'renewable energy', 'a job interview', 'ancient Rome',
        'a family road trip', 'online privacy', 'a cooking disaster'
    ])[floor(random() * 12 + 1)]
    || '. (Prompt #' || i || ')',
    -- messy category casing/whitespace, picked at random per row
    (ARRAY[
        'summarization', 'Summarization', 'SUMMARIZATION',
        'grammar_explanation', 'Grammar_Explanation', ' grammar_explanation',
        'translation', 'Translation', 'translation ',
        'creative_writing', 'Creative_Writing', 'creative_writing  ',
        'coding', 'Coding', ' coding'
    ])[floor(random() * 15 + 1)],
    (ARRAY['easy', 'medium', 'hard'])[floor(random() * 3 + 1)]
FROM generate_series(1, 2000) AS s(i);

-- Inject ~40 exact duplicate prompts to simulate an accidental
-- double import, a common issue when combining or importing data.
INSERT INTO prompts (prompt_text, category, difficulty_level)
SELECT prompt_text, category, difficulty_level
FROM prompts
WHERE prompt_id <= 5000
ORDER BY random()
LIMIT 40;


-- ---------------------------------------------------------------------
-- 3. AI responses: every prompt gets a response from every model.
--    A small subset gets extra leading/trailing whitespace in the
--    response text, and a small subset gets a NULL word_count, to
--    simulate incomplete data capture.
-- ---------------------------------------------------------------------
INSERT INTO ai_responses (prompt_id, model_id, response_text, word_count, latency_ms)
SELECT
    p.prompt_id,
    m.model_id,
    CASE
        WHEN random() < 0.05 THEN
            '   Response generated by ' || m.model_name || ' for prompt ' || p.prompt_id || '. '
                || repeat('This synthetic sentence stands in for generated content. ', floor(random() * 4 + 2)::int) || '   '
        ELSE
            'Response generated by ' || m.model_name || ' for prompt ' || p.prompt_id || '. '
                || repeat('This synthetic sentence stands in for generated content. ', floor(random() * 4 + 2)::int)
    END,
    CASE WHEN random() < 0.03 THEN NULL ELSE floor(random() * 200 + 20)::int END,
    floor(random() * 2000 + 300)::int
FROM prompts p
CROSS JOIN llm_models m
WHERE p.prompt_id > 5;  -- -- Skip the original seed prompts because they already have responses.


-- ---------------------------------------------------------------------
-- 4. Evaluations: each response gets scored by a random subset of
--    evaluators across a random subset of criteria.
-- ---------------------------------------------------------------------
INSERT INTO evaluations (response_id, evaluator_id, criteria_id, score, comments)
SELECT
    r.response_id,
    e.evaluator_id,
    c.criteria_id,
    ROUND((random() * 6 + 4)::numeric, 1),
    NULL
FROM ai_responses r
CROSS JOIN evaluators e
CROSS JOIN evaluation_criteria c
WHERE random() < 0.15
  AND r.response_id > 5
ON CONFLICT (response_id, evaluator_id, criteria_id) DO NOTHING;


-- ---------------------------------------------------------------------
-- Sanity check: row counts after generation
-- ---------------------------------------------------------------------
SELECT 'prompts' AS table_name, COUNT(*) FROM prompts
UNION ALL
SELECT 'ai_responses', COUNT(*) FROM ai_responses
UNION ALL
SELECT 'evaluators', COUNT(*) FROM evaluators
UNION ALL
SELECT 'evaluations', COUNT(*) FROM evaluations;
